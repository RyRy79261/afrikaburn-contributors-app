import {
  Accessibility,
  BatteryCharging,
  Bed,
  Bike,
  Box,
  Bus,
  Car,
  Caravan,
  CircleDot,
  CircleSmall,
  Container,
  CookingPot,
  DoorOpen,
  Droplets,
  Flame,
  Footprints,
  Fuel,
  Music,
  Package,
  ShieldAlert,
  ShowerHead,
  Siren,
  Speaker,
  SquareDashed,
  Store,
  Sun,
  SunMedium,
  Tent,
  TentTree,
  Toilet,
  Trash,
  Truck,
  Wine,
  Zap,
  type LucideIcon,
} from "lucide-react";

// The catalogue names an icon (@quagga/core layout-catalog.ts never imports
// one); this maps the name to lucide. An unknown name gets a plain box.
const ICONS: Record<string, LucideIcon> = {
  accessibility: Accessibility,
  "battery-charging": BatteryCharging,
  bed: Bed,
  bike: Bike,
  bus: Bus,
  car: Car,
  caravan: Caravan,
  "circle-dot": CircleDot,
  "circle-small": CircleSmall,
  container: Container,
  "cooking-pot": CookingPot,
  "door-open": DoorOpen,
  droplets: Droplets,
  flame: Flame,
  footprints: Footprints,
  fuel: Fuel,
  music: Music,
  package: Package,
  "shield-alert": ShieldAlert,
  "shower-head": ShowerHead,
  siren: Siren,
  speaker: Speaker,
  "square-dashed": SquareDashed,
  store: Store,
  sun: Sun,
  "sun-medium": SunMedium,
  tent: Tent,
  "tent-tree": TentTree,
  toilet: Toilet,
  "trash-2": Trash,
  truck: Truck,
  wine: Wine,
  zap: Zap,
};

export function layoutIcon(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || Box;
}
