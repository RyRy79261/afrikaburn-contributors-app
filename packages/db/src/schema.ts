// --- Notifications -------------------------------------------------------
// Per-account inbox. Append-only; `read_at` set on open ("mark all read" bulk-
// sets it). Generated by EXISTING events (registration decisions, wrangler
// assignment, role/officer acceptance, questionnaire release, supplier org-
// confirmations, security events) + bulletin fan-out. `bulletin_id` links a
// `bulletin`-kind row back to its source. NO new PII — previews never carry
// hard-locked fields (enforced by the @quagga/core payload builders).

export const notifications = pgTable(
  "notifications",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    kind: notificationKindEnum("kind").notNull(),
    title: text("title").notNull(),
    body: text("body"),
    link: text("link"),
    /**
     * WHO SENT IT (migration 0021) — `org`, `camp`, or `system`.
     *
     * Provenance, and only provenance: "AfrikaBurn asked you this" and "your
     * camp lead asked you this" are different things to the person reading the
     * inbox, and nothing on the row said which.
     */
    origin: text("origin"),
    /**
     * WHICH APP THE LINK RESOLVES IN (migration 0021) — `web`, `org` or
     * `suppliers`.
     *
     * Deliberately SEPARATE from `origin`, because they genuinely differ: the
     * org console writes the supplier inbox, so those rows are sent BY org and
     * read IN the suppliers app. Conflating the two is what produced the proven
     * 404 — one table, three apps, and a bare app-relative `link` that means a
     * different route depending on who reads it.
     *
     * Nullable on purpose. All three apps run migrations at build time, so
     * whichever deploys first would otherwise be writing a column the other two
     * do not yet bind — and every notification insert swallows its own
     * exception, so that failure would be silent. Null means "unknown, treat as
     * local", which is exactly the pre-migration behaviour.
     */
    linkApp: text("link_app"),
    bulletinId: uuid("bulletin_id").references(() => bulletins.id, {
      onDelete: "cascade",
    }),
    createdAt: timestamp("created_at", { mode: "date" }).notNull().defaultNow(),
    readAt: timestamp("read_at", { mode: "date" }),
  },
  (n) => ({
    // Unread count + filter: (user, read_at).
    userReadIdx: index("notifications_user_read_idx").on(n.userId, n.readAt),
    // Inbox list, newest first: (user, created_at desc).
    userCreatedIdx: index("notifications_user_created_idx").on(
      n.userId,
      n.createdAt.desc(),
    ),
  }),
);

// --- Account deletion requests -------------------------------------------
// docs/accounts-security-spec.md §Deletion. Deleting an account is NEVER a row
// delete. Re-auth to request → a 14-day grace period (cancelled by simply
// signing in) → then SANITIZATION (the Camp 404 "Lost Cat" precedent): personal
// fields are erased and the identity is anonymized to a "Departed Burner" stub
// so memberships, questionnaire responses, and audit events keep referential
// integrity and POPIA erasure is still satisfied.
//
// `grace_ends_at` is STORED rather than derived from `requested_at + 14d` on
// read: a later policy change to the grace length must never retroactively
// shorten a window someone was already promised.
//
// One LIVE request per user is enforced by a partial unique index (`WHERE
// status = 'pending'`), not a plain unique on `user_id`: a burner who cancels
// and later changes their mind must be able to request again.

export const accountDeletionRequests = pgTable(
  "account_deletion_requests",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    status: accountDeletionStatusEnum("status").notNull().default("pending"),
    requestedAt: timestamp("requested_at", { mode: "date" })
      .notNull()
      .defaultNow(),
    /** When the grace period elapses and sanitization becomes due. */
    graceEndsAt: timestamp("grace_ends_at", { mode: "date" }).notNull(),
    cancelledAt: timestamp("cancelled_at", { mode: "date" }),
    /** Set when sanitization has actually been applied. */
    completedAt: timestamp("completed_at", { mode: "date" }),
    /** Which app the request came from (`web` | `org` | `suppliers`) — trail only. */
    requestedFromApp: text("requested_from_app"),
    createdAt: timestamp("created_at", { mode: "date" }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { mode: "date" }).notNull().defaultNow(),
  },
  (r) => ({
    userStatusIdx: index("account_deletion_requests_user_status_idx").on(
      r.userId,
      r.status,
    ),
    // The sweeper's query: pending requests whose grace has elapsed.
    dueIdx: index("account_deletion_requests_due_idx").on(
      r.status,
      r.graceEndsAt,
    ),
    // At most one PENDING request per user; cancelled/completed rows stay as
    // history and never block a fresh request.
    onePendingPerUser: uniqueIndex("account_deletion_requests_one_pending_idx")
      .on(r.userId)
      .where(sql`${r.status} = 'pending'`),
  }),
);

// --- Email change requests -----------------------------------------------
// docs/accounts-security-spec.md §"Email change": confirm via the NEW address,
// notify the OLD address with a revocation link, revocable for 48h.
//
// WHY WE OWN THIS TABLE. Managed Neon Auth's SERVER SDK exposes no
// `change-email` endpoint (its typed endpoint allowlist covers change-password,
// request/reset-password, verify-email, list/revoke-sessions, delete-user — but
// not change-email), and we cannot add a Better Auth server plugin on a managed
// instance. Even if the browser client's `changeEmail` reaches the upstream
// instance through the `/api/auth/*` proxy, Better Auth's own flow has no 48h
// revocation window — that requirement is OURS regardless of the provider. So
// this table is the record of the request, the confirmation, and the revocation
// window; committing the new address at the identity provider is a separate,
// explicitly-gated step that FAILS SAFE when the provider cannot do it (see
// `@quagga/core` AUTH_CAPABILITIES and the app-side commit seam). A row here is
// never treated as proof the address changed — only `status = 'confirmed'` plus
// a successful provider commit is.
//
// Tokens are stored as SHA-256 HASHES, never plaintext: a database leak must
// not hand an attacker a live confirmation or revocation link.

export const emailChangeRequests = pgTable(
  "email_change_requests",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    /** The address at request time — the one that gets the revocation notice. */
    currentEmail: text("current_email").notNull(),
    newEmail: text("new_email").notNull(),
    status: emailChangeStatusEnum("status").notNull().default("pending"),
    /** SHA-256 of the single-use confirmation token emailed to the NEW address. */
    confirmTokenHash: text("confirm_token_hash").notNull().unique(),
    /** SHA-256 of the revocation token emailed to the OLD address. */
    revokeTokenHash: text("revoke_token_hash").notNull().unique(),
    /** Confirmation-token expiry (short-lived, enumeration-safe). */
    expiresAt: timestamp("expires_at", { mode: "date" }).notNull(),
    confirmedAt: timestamp("confirmed_at", { mode: "date" }),
    /** confirmedAt + 48h; stored so a policy change can't shrink a live window. */
    revocableUntil: timestamp("revocable_until", { mode: "date" }),
    revokedAt: timestamp("revoked_at", { mode: "date" }),
    /**
     * Set only when the address was actually changed AT THE IDENTITY PROVIDER.
     * Null on a `confirmed` row means the provider commit has not happened (or
     * is not currently possible) — the app must never present that as success.
     */
    providerCommittedAt: timestamp("provider_committed_at", { mode: "date" }),
    createdAt: timestamp("created_at", { mode: "date" }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { mode: "date" }).notNull().defaultNow(),
  },
  (r) => ({
    userStatusIdx: index("email_change_requests_user_status_idx").on(
      r.userId,
      r.status,
    ),
    // At most one PENDING (unconfirmed) request per user — a second request
    // supersedes the first, which the action cancels before inserting. Confirmed
    // rows are excluded so the 48h revocation history survives.
    onePendingPerUser: uniqueIndex("email_change_requests_one_pending_idx")
      .on(r.userId)
      .where(sql`${r.status} = 'pending'`),
  }),
);

// --- Security events ------------------------------------------------------
// docs/accounts-security-spec.md §"recent security events". An append-only log of
// what actually happened to an account, recorded at the moment each account action
// succeeds. This REPLACES the earlier stopgap where the security page derived its
// feed from `notifications` (which conflated inbox messages with the event record).
//
// Recording is THIN and BEST-EFFORT — a failed insert here must never roll back
// (or fail) the primary security action it describes. `ip`/`user_agent` are the
// request context at the time of the event (both nullable — not every event has a
// request, e.g. the sign-in-driven deletion cancel). `kind` is the typed event
// class (mirrors SecurityEventLogKind in @quagga/types; display strings come from
// @quagga/core `describeSecurityEvent` so no PII/labels are stored here).
export const securityEvents = pgTable(
  "security_events",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    kind: securityEventKindEnum("kind").notNull(),
    ip: text("ip"),
    userAgent: text("user_agent"),
    createdAt: timestamp("created_at", { mode: "date" }).notNull().defaultNow(),
  },
  (e) => ({
    // The feed query: an account's events, newest first.
    userCreatedIdx: index("security_events_user_created_idx").on(
      e.userId,
      e.createdAt.desc(),
    ),
  }),
);
